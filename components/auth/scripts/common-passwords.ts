// Writes `src/components/password/commonPasswords.generated.ts` (STUDY-201 §1.6, STUDY-208 §1.11): the union of the
// 3000 most frequent passwords of 8 code points or more (the component's floor) and the 3000 most frequent of 10 or
// more (the methods' minimum) from SecLists' NCSC list, as v2.0.0's generator selects them (`5e9501ee`: NFC, then
// lowercase; deduplicated in that form; in the list's order of frequency), keyed by length, each length sorted for a
// binary search.
//
//   bun components/auth/scripts/common-passwords.ts
//
// It fetches that one file of SecLists (a full clone is about 1 GB): a shallow, blobless, sparse clone in a temporary
// directory, removed after.
import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { DEFAULT_MIN_PASSWORD_LENGTH } from "../src/lib/password.ts";

const REPOSITORY = "https://github.com/danielmiessler/SecLists";
// The UK NCSC's and Have I Been Pwned's list, in order of frequency throughout. (Not xato-net's million: only its first
// 5000 lines are by frequency, the rest alphabetical.)
const SOURCE = "Passwords/Common-Credentials/100k-most-used-passwords-NCSC.txt";
/** The component's floor (`MIN_PASSWORD_LENGTH`): shorter passwords are refused by the length rule already. */
const MIN_LENGTH = 8;
/** The password methods' minimum for a new password. */
const METHOD_MIN_LENGTH = DEFAULT_MIN_PASSWORD_LENGTH;
/** How many of each: an app with either minimum gets a full list. */
const COUNT = 3000;
const OUTPUT = fileURLToPath(new URL("../src/components/password/commonPasswords.generated.ts", import.meta.url));

const git = (...args: string[]) => execFileSync("git", args, { stdio: ["ignore", "ignore", "inherit"] });
const codePoints = (s: string) => [...s].length;

function fetchSource(): string {
  const dir = mkdtempSync(join(tmpdir(), "seclists-"));
  try {
    const clone = join(dir, "SecLists");
    git("clone", "--quiet", "--depth=1", "--filter=blob:none", "--sparse", `${REPOSITORY}.git`, clone);
    git("-C", clone, "sparse-checkout", "set", "--no-cone", `/${SOURCE}`);
    return readFileSync(join(clone, SOURCE), "utf8");
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}

/**
 * The most frequent passwords long enough, in the lookup's form, first seen first: one is kept while fewer than
 * {@link COUNT} distinct passwords of {@link MIN_LENGTH} or more came before it, or, for one of
 * {@link METHOD_MIN_LENGTH} or more, while fewer than {@link COUNT} of those did.
 */
function select(text: string): string[] {
  const picked: string[] = [];
  const seen = new Set<string>();
  // The distinct passwords seen so far: all of them, and those of the methods' length.
  let listCount = 0;
  let methodCount = 0;
  for (const line of text.split("\n")) {
    const password = line.replace(/\r$/, "");
    if (password === "") continue;
    // Lowercased after NFC, as the lookup does; measured after, since lowercasing can change the length.
    const form = password.normalize("NFC").toLowerCase();
    if (codePoints(form) < MIN_LENGTH || seen.has(form)) continue;
    seen.add(form);
    const forMethods = codePoints(form) >= METHOD_MIN_LENGTH;
    if (listCount < COUNT || (forMethods && methodCount < COUNT)) picked.push(form);
    listCount++;
    if (forMethods) methodCount++;
    if (listCount >= COUNT && methodCount >= COUNT) break;
  }
  if (methodCount < COUNT)
    throw new Error(
      `The source list contains only ${methodCount} passwords with ${METHOD_MIN_LENGTH} characters or more, but ` +
        `${COUNT} are necessary.`,
    );
  return picked;
}

function render(passwords: string[]): string {
  const byLength = new Map<number, string[]>();
  for (const p of passwords) {
    const n = codePoints(p);
    byLength.set(n, [...(byLength.get(n) ?? []), p]);
  }
  // JavaScript's default sort (UTF-16 code units): the comparison the lookup's `<` makes.
  const rows = [...byLength.keys()]
    .sort((a, b) => a - b)
    .map(
      (n) =>
        `  ${n}: [${byLength
          .get(n)!
          .sort()
          .map((p) => JSON.stringify(p))
          .join(",")}],`,
    );
  return `// The ${COUNT} most frequent passwords of ${MIN_LENGTH} characters or more and the ${COUNT} most frequent of
// ${METHOD_MIN_LENGTH} or more, NFC and lowercase, keyed by their length in code points, each length sorted.
// Generated by \`bun components/auth/scripts/common-passwords.ts\`: do not edit.
//
// Source: ${SOURCE} in SecLists (MIT license, ${REPOSITORY}), from the UK National Cyber Security
// Centre and Have I Been Pwned.
// biome-ignore-all format: generated

/** The most frequent passwords, by length in code points, each length sorted. */
export const COMMON_PASSWORDS_BY_LENGTH: Record<number, readonly string[]> = {
${rows.join("\n")}
};
`;
}

const passwords = select(fetchSource());
writeFileSync(OUTPUT, render(passwords));
console.log(`Wrote ${passwords.length} passwords to ${OUTPUT}`);
