// Writes `src/components/password/commonPasswords.generated.ts` (STUDY-201 §1.6): the 3000 most frequent passwords of
// 10 code points or more from SecLists' NCSC list, as v2's generator selects them (NFC, then lowercase; deduplicated in
// that form; in the list's order of frequency), keyed by length, each length sorted for a binary search.
//
//   bun components/auth/scripts/common-passwords.ts
//
// It fetches that one file of SecLists (a full clone is about 1 GB): a shallow, blobless, sparse clone in a temporary
// directory, removed after.
import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const REPOSITORY = "https://github.com/danielmiessler/SecLists";
// The UK NCSC's and Have I Been Pwned's list, in order of frequency throughout. (Not xato-net's million: only its first
// 5000 lines are by frequency, the rest alphabetical.)
const SOURCE = "Passwords/Common-Credentials/100k-most-used-passwords-NCSC.txt";
/** Shorter passwords are refused by the length rule already. */
const MIN_LENGTH = 10;
const COUNT = 3000;
const OUTPUT = fileURLToPath(new URL("../src/components/password/commonPasswords.generated.ts", import.meta.url));

const git = (...args: string[]) => execFileSync("git", args, { stdio: ["ignore", "ignore", "inherit"] });
const codePoints = (s: string) => [...s].length;

function fetchSource(): string {
  const dir = mkdtempSync(join(tmpdir(), "seclists-"));
  try {
    const clone = join(dir, "SecLists");
    git("clone", "--quiet", "--depth=1", "--filter=blob:none", "--sparse", `${REPOSITORY}.git`, clone);
    git("-C", clone, "sparse-checkout", "set", "--no-cone", `/${SOURCE}`);
    return readFileSync(join(clone, SOURCE), "utf8");
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}

/** The most frequent passwords long enough, in the lookup's form, first seen first. */
function select(text: string): string[] {
  const picked = new Set<string>();
  for (const line of text.split("\n")) {
    const password = line.replace(/\r$/, "");
    if (password === "") continue;
    // Lowercased after NFC, as the lookup does; measured after, since lowercasing can change the length.
    const form = password.normalize("NFC").toLowerCase();
    if (codePoints(form) < MIN_LENGTH) continue;
    picked.add(form);
    if (picked.size === COUNT) return [...picked];
  }
  throw new Error(`The source has only ${picked.size} passwords of ${MIN_LENGTH} characters or more, not ${COUNT}.`);
}

function render(passwords: string[]): string {
  const byLength = new Map<number, string[]>();
  for (const p of passwords) {
    const n = codePoints(p);
    byLength.set(n, [...(byLength.get(n) ?? []), p]);
  }
  // JavaScript's default sort (UTF-16 code units): the comparison the lookup's `<` makes.
  const rows = [...byLength.keys()]
    .sort((a, b) => a - b)
    .map(
      (n) =>
        `  ${n}: [${byLength
          .get(n)!
          .sort()
          .map((p) => JSON.stringify(p))
          .join(",")}],`,
    );
  return `// The ${COUNT} most frequent passwords of ${MIN_LENGTH} characters or more, NFC and lowercase, keyed by their length in
// code points, each length sorted. Generated by \`bun components/auth/scripts/common-passwords.ts\`: do not edit.
//
// Source: ${SOURCE} in SecLists (MIT license, ${REPOSITORY}), from the UK National Cyber Security
// Centre and Have I Been Pwned.
// biome-ignore-all format: generated

/** The most frequent passwords, by length in code points, each length sorted. */
export const COMMON_PASSWORDS_BY_LENGTH: Record<number, readonly string[]> = {
${rows.join("\n")}
};
`;
}

const passwords = select(fetchSource());
writeFileSync(OUTPUT, render(passwords));
console.log(`Wrote ${passwords.length} passwords to ${OUTPUT}`);
