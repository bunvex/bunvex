// Generates packages/server/src/unidecode-table.ts (STUDY-141, DV-450): the transliteration Convex's streaming
// import slugifies names with (the `slugify` 0.1.0 crate over `unidecode` 0.3.0), reduced to what a slug keeps.
//
//   bun scripts/generate-unidecode-table.ts <path to unidecode-0.3.0/src/data.rs>
//
// Get the crate from https://static.crates.io/crates/unidecode/unidecode-0.3.0.crate (sha256
// 402bb19d8e03f1d1a7450e2bd613980869438e0666331be3e073089124aa1adc, the checksum in Convex's Cargo.lock) and
// extract it. `data.rs` holds one string per code point from U+0000 to U+FFFE; a code point past it maps to "".
//
// A slug keeps only `a–z0–9` of the lower-cased transliteration and turns every other run into one `_`, so each
// entry is stored that way: lower-cased, each run of other characters as one `_` ("Bei " → "bei_", "[?]" → "_").
// An empty entry stays empty (it joins its neighbours). Only U+0080 up are stored; ASCII maps to itself.
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const src = process.argv[2];
if (!src) throw new Error("usage: bun scripts/generate-unidecode-table.ts <unidecode-0.3.0/src/data.rs>");
const text = readFileSync(src, "utf8");
const entries: string[] = [];
for (const line of text.split("\n")) {
  const m = /^\s*"((?:\\u\{[0-9a-f]+\})*)",$/.exec(line);
  if (!m) continue;
  entries.push(m[1]!.replace(/\\u\{([0-9a-f]+)\}/g, (_, h: string) => String.fromCodePoint(Number.parseInt(h, 16))));
}
if (entries.length !== 0xffff) throw new Error(`expected 65535 entries, found ${entries.length}`);
const reduce = (s: string) => s.toLowerCase().replace(/[^a-z0-9]+/g, "_");
const reduced = entries.slice(0x80).map(reduce);
// The crate's license, reproduced as its BSD-3-Clause terms ask.
const license = readFileSync(resolve(src, "../../LICENSE"), "utf8")
  .trimEnd()
  .split("\n")
  .map((l) => `// ${l}`.trimEnd())
  .join("\n");
const out = `// Generated by scripts/generate-unidecode-table.ts from the \`unidecode\` 0.3.0 crate (rust-unidecode; its data
// ported from Sean M. Burke's Text::Unidecode). Do not edit.
// Entry k (comma-separated) is U+0080 + k, reduced to what a slug keeps (see the script).
//
${license}
export const UNIDECODE_SLUG_TABLE =
  ${JSON.stringify(reduced.join(","))};
`;
const target = resolve(import.meta.dir, "../packages/server/src/unidecode-table.ts");
writeFileSync(target, out);
console.log(`wrote ${target}: ${reduced.length} entries, ${out.length} bytes`);
